-- Contamination Tracker - Supabase schema. Run once in Supabase > SQL Editor.
-- Streamlit writes with the service key (server only). The service key bypasses RLS.
-- The APK uses the anon key plus a signed-in user, so everything below is locked down with RLS.

create table if not exists units(
  id text primary key, name text not null, maker text, kind text, fleet integer default 0,
  hm text, descr text, ts double precision default 0);
create table if not exists unit_spec(
  unit_id text not null, label text not null, value text, src text default 'indikatif',
  primary key(unit_id, label));
create table if not exists parts(
  id text primary key, unit_id text not null, name text not null, part_no text default '—',
  system text default 'Lainnya', asm text default 'Umum', kind text default 'bolt',
  type text default 'metal', material text default '—', l double precision default 100,
  w double precision default 100, h double precision default 100, qty integer default 1,
  fm integer default 1, incidents integer default 0, note text default '', color text default '#5d636a');
create index if not exists idx_parts_unit on parts(unit_id);
create table if not exists history(
  id bigint generated by default as identity primary key, part_id text not null, date text,
  hm double precision, reason text);
create table if not exists photos(
  id bigint generated by default as identity primary key, part_id text not null, role text not null,
  file text not null);
create table if not exists inspections(
  lambung text not null, part_id text not null, status text not null, date text, note text,
  primary key(lambung, part_id));
create table if not exists cases(
  id bigint generated by default as identity primary key, date text, loc text, unit_id text,
  part_id text, lambung text, note text, builtin integer default 0);
create table if not exists operations(
  date text not null, lambung text not null, area text, primary key(date, lambung));
create table if not exists users(
  username text primary key, name text, role text not null, pw_hash text not null,
  active integer default 1, must_change integer default 0, created text);
create table if not exists audit(
  id bigint generated by default as identity primary key, ts text, "user" text, action text, detail text);

-- Field data sent by the APK (Scenario B). It waits here until an admin approves it.
create table if not exists field_submissions(
  id uuid primary key default gen_random_uuid(),
  device_id text not null, submitted_by uuid default auth.uid(),
  kind text not null check (kind in ('case','inspection','photo')),
  payload jsonb not null, status text not null default 'pending' check (status in ('pending','approved','rejected')),
  created_at timestamptz default now(), reviewed_by text, reviewed_at timestamptz);

-- Row Level Security: on for every table. No policy = no access for anon/authenticated.
do $$ declare t text; begin
  foreach t in array array['units','unit_spec','parts','history','photos','inspections','cases','operations',
                           'users','audit','field_submissions'] loop
    execute format('alter table %I enable row level security', t);
  end loop; end $$;

-- Signed-in app users may READ catalog data (not users or audit).
do $$ declare t text; begin
  foreach t in array array['units','unit_spec','parts','history','photos','inspections','cases','operations'] loop
    execute format('drop policy if exists "read_%1$s" on %1$I', t);
    execute format('create policy "read_%1$s" on %1$I for select to authenticated using (true)', t);
  end loop; end $$;

-- Signed-in users may add field submissions and see only their own. Only the server (service key) approves.
drop policy if exists "fs_insert" on field_submissions;
create policy "fs_insert" on field_submissions for insert to authenticated
  with check (submitted_by = auth.uid() and status = 'pending');
drop policy if exists "fs_read_own" on field_submissions;
create policy "fs_read_own" on field_submissions for select to authenticated using (submitted_by = auth.uid());

-- Private bucket for photos and 3D models. Signed-in users may download; only the server uploads.
insert into storage.buckets(id, name, public) values ('ct-files', 'ct-files', false) on conflict (id) do nothing;
drop policy if exists "ct_files_read" on storage.objects;
create policy "ct_files_read" on storage.objects for select to authenticated using (bucket_id = 'ct-files');
